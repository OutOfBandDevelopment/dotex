import { mkdirSync, rmSync, writeFileSync } from 'node:fs';
import { resolve } from 'node:path';
import type { Journey } from './journey';

/** Where the generated guides, specs and screenshots go (repo root docs/example). */
export const docsRoot = process.env.E2E_DOCS_DIR ?? resolve(process.cwd(), '../../../docs/example');

export interface ShotRecord { step: number; file: string }

export const slug = (s: string) => s.toLowerCase().replace(/[^a-z0-9]+/g, '-').replace(/^-|-$/g, '');

const banner = (kind: string) =>
  `<!-- Generated by the Playwright journeys (src/Examples/OoBDev.Example.Web/e2e). Do not edit by hand: change the journey and rerun \`npm run e2e\`. This ${kind} is rebuilt on every run. -->\n`;

export function imageDir(journey: Journey): string {
  const dir = resolve(docsRoot, 'user-guide', 'images', journey.id);
  mkdirSync(dir, { recursive: true });
  return dir;
}

export function stepImageName(index: number, title: string): string {
  return `${String(index + 1).padStart(2, '0')}-${slug(title)}.png`;
}

export function resetImages(journey: Journey): void {
  rmSync(resolve(docsRoot, 'user-guide', 'images', journey.id), { recursive: true, force: true });
}

const diagram = (j: Journey) => [
  '```plantuml',
  '@startuml',
  'skinparam shadowing false',
  'start',
  ...j.steps.map(s => `:${s.title};`),
  'stop',
  '@enduml',
  '```',
].join('\n');

/** The user guide for one journey: goal, prerequisites, flow diagram and a screenshot per step. */
export function writeGuide(j: Journey): void {
  const out: string[] = [banner('guide'), `# ${j.title}\n`];
  out.push(`[User guides](README.md) | [Spec](../specs/${j.id}.md)\n`);
  out.push('## Contents\n');
  out.push('- [Goal](#goal)', '- [Before you start](#before-you-start)', '- [Journey at a glance](#journey-at-a-glance)', '- [Steps](#steps)', '');
  out.push(`## Goal\n\n**Who:** ${j.persona}.\n\n${j.goal}\n`);
  out.push('## Before you start\n');
  out.push(j.prerequisites.length ? j.prerequisites.map(p => `- ${p}`).join('\n') : '- Nothing beyond a running example stack.');
  out.push('', `Related framework features: ${j.features.join('; ')}.\n`);
  out.push('## Journey at a glance\n', diagram(j), `\n*Figure 1 — ${j.title}: the steps in order*\n`);
  out.push('## Steps\n');
  j.steps.forEach((s, i) => {
    out.push(`### ${i + 1}. ${s.title}\n`, `${s.narrative}\n`);
    out.push(`![${s.title}](images/${j.id}/${stepImageName(i, s.title)})\n`);
    out.push(`*Figure ${i + 2} — ${s.title}*\n`);
  });
  write(resolve(docsRoot, 'user-guide', `${j.id}.md`), out.join('\n'));
}

/** The executable specification: every acceptance criterion the journey asserts. */
export function writeSpec(j: Journey): void {
  const out: string[] = [banner('spec'), `# Spec: ${j.title}\n`];
  out.push(`[Specs](README.md) | [User guide](../user-guide/${j.id}.md)\n`);
  out.push(`**Start:** \`${j.start}\`  \n**Persona:** ${j.persona}  \n**Goal:** ${j.goal}\n`);
  out.push('**Table 1 — Acceptance criteria**\n');
  out.push('| Step | Action | Expected result |', '| --- | --- | --- |');
  j.steps.forEach((s, i) => out.push(`| ${i + 1} | ${s.title} | ${s.expect.join('<br>')} |`));
  out.push('', `Source: \`e2e/journeys.ts\` (journey \`${j.id}\`). Each expected result is asserted by the step's \`run\` function.\n`);
  write(resolve(docsRoot, 'specs', `${j.id}.md`), out.join('\n'));
}

export function writeIndexes(journeys: Journey[]): void {
  const guide = [banner('index'), '# Example user guides\n', '[Example documentation](../README.md)\n',
    'Step-by-step guides with screenshots, one per user journey. They are regenerated by the end-to-end tests, so they always match the application.\n',
    '**Table 1 — User journeys**\n', '| Journey | Who | Goal |', '| --- | --- | --- |',
    ...journeys.map(j => `| [${j.title}](${j.id}.md) | ${j.persona} | ${j.goal} |`), ''];
  write(resolve(docsRoot, 'user-guide', 'README.md'), guide.join('\n'));

  const specs = [banner('index'), '# Example specifications\n', '[Example documentation](../README.md)\n',
    'Acceptance criteria for each journey. The same journeys run as Playwright tests.\n',
    '**Table 1 — Specifications**\n', '| Spec | Steps | Start route |', '| --- | --- | --- |',
    ...journeys.map(j => `| [${j.title}](${j.id}.md) | ${j.steps.length} | \`${j.start}\` |`), ''];
  write(resolve(docsRoot, 'specs', 'README.md'), specs.join('\n'));
}

function write(path: string, content: string): void {
  mkdirSync(resolve(path, '..'), { recursive: true });
  writeFileSync(path, content.replace(/\r?\n/g, '\n'), 'utf8');
}
