using System;
using System.Collections.Generic;
using System.IO;
using System.Linq;
using System.Text;
using System.Text.RegularExpressions;

namespace OoBDev.Docs.Tests;

/// <summary>
/// Builds the per-project catalog under <c>docs/patterns-discovery/07-project-catalog</c>: one file per layer folder in <c>src</c>,
/// one table row per non-test project (name, first sentence of its readme, review flags), with navigation and contents.
/// Deterministic: the same tree gives the same bytes.
/// </summary>
public static class ProjectCatalog
{
    /// <summary>The layer folders under <c>src</c>, in catalog order.</summary>
    public static readonly IReadOnlyList<string> Layers =
        ["Common", "Framework", "Extensions", "ExternalServices", "HardwareDevices", "Tools", "Examples", "Applications", "Spikes"];

    private static readonly string[] _skip = ["bin", "obj", "node_modules"];
    private static readonly Regex _comments = new("<!--.*?-->", RegexOptions.Singleline, TimeSpan.FromSeconds(5));
    private static readonly Regex _fences = new("```.*?```", RegexOptions.Singleline, TimeSpan.FromSeconds(5));
    private static readonly Regex _links = new(@"\[([^\]]*)\]\([^)]*\)", RegexOptions.None, TimeSpan.FromSeconds(5));
    private static readonly Regex _sentence = new(@"^(.{20,220}?[.!?])(\s|$)", RegexOptions.None, TimeSpan.FromSeconds(5));
    private static readonly Regex _paragraphs = new(@"\n\s*\n", RegexOptions.None, TimeSpan.FromSeconds(5));

    /// <summary>The catalog files for the repository at <paramref name="root"/>: file name to content (LF endings).</summary>
    public static IReadOnlyDictionary<string, string> Build(string root)
    {
        var files = new SortedDictionary<string, string>(StringComparer.Ordinal);
        var present = Layers.Where(l => Directory.Exists(Path.Combine(root, "src", l))).ToList();
        var names = present.Select((l, i) => $"{i + 1:00}-{l.ToLowerInvariant()}.md").ToList();
        for (var i = 0; i < present.Count; i++)
        {
            var previous = i == 0 ? "[← Index](./README.md)" : $"[← {present[i - 1]} Layer](./{names[i - 1]})";
            var next = i == present.Count - 1 ? "[Index →](./README.md)" : $"[{present[i + 1]} Layer →](./{names[i + 1]})";
            files[names[i]] = Layer(root, present[i], i + 1, previous, next);
        }

        files["README.md"] = Readme(present, names);
        return files;
    }

    /// <summary>Writes <see cref="Build"/> to <paramref name="folder"/>, touching only files whose content differs (line endings ignored); returns the names written.</summary>
    public static IReadOnlyList<string> Write(string root, string folder)
    {
        var written = new List<string>();
        Directory.CreateDirectory(folder);
        foreach (var (name, content) in Build(root))
        {
            var path = Path.Combine(folder, name);
            if (File.Exists(path) && File.ReadAllText(path).Replace("\r\n", "\n", StringComparison.Ordinal) == content)
            {
                continue;
            }

            File.WriteAllText(path, content, new UTF8Encoding(false));
            written.Add(name);
        }

        return written;
    }

    private static string Layer(string root, string layer, int number, string previous, string next)
    {
        var all = Projects(Path.Combine(root, "src", layer));
        var names = all.Select(p => p.Name).ToHashSet(StringComparer.Ordinal);
        var production = all.Where(p => !IsTest(p.Name)).ToList();
        var rows = new List<string>();
        foreach (var (directory, name) in production)
        {
            var (purpose, hasReadme) = Purpose(directory, name);
            var stem = name.EndsWith(".Abstractions", StringComparison.Ordinal) ? name[..^".Abstractions".Length] : name;
            var hasTests = names.Any(t => t.StartsWith(stem + ".Tests", StringComparison.Ordinal) || t == stem + "Tests");
            var flags = new List<string>();
            if (!hasReadme)
            {
                flags.Add("no readme");
            }

            if (!hasTests && layer == "Framework" && !name.EndsWith(".Abstractions", StringComparison.Ordinal))
            {
                flags.Add("no tests project");
            }

            rows.Add($"| `{name}` | {(purpose.Length > 0 ? purpose : " ")} | {(flags.Count > 0 ? string.Join(", ", flags) : " ")} |");
        }

        var text = new List<string>
        {
            $"# {layer} Layer", "",
            "<!-- nav -->", $"[↑ 07 — Project Catalog](./README.md) · {previous} · {next}", "<!-- nav -->", "",
            $"Generated by the `ProjectCatalogTests` generation test in `src/Tools/OoBDev.Docs.Tests` from `src/{layer}`; do not edit by hand. "
            + "Purpose is the first sentence of the project readme. Flags mark owner-review items "
            + "(a Framework project without a tests project or a project without a readme).", "",
            $"{production.Count} projects (test projects excluded).", "",
            $"**Table {number} — {layer} projects**", "",
            "| Project | Purpose | Review flags |", "|---------|---------|--------------|",
        };
        text.AddRange(rows);
        text.AddRange(["", "---", "", "<!-- nav -->", $"[↑ 07 — Project Catalog](./README.md) · {previous} · {next}", "<!-- nav -->", ""]);
        return string.Join('\n', text);
    }

    private static string Readme(List<string> layers, List<string> names)
    {
        var text = new List<string>
        {
            "# 07 — Project Catalog", "",
            "One line per project, grouped by layer ([architecture](../01-architecture/README.md)). Generated from the source tree, "
            + "so it stays current: run `dotnet test src/Tools/OoBDev.Docs.Tests --filter FullyQualifiedName~ProjectCatalogTests` (the generation test rewrites the files that changed). "
            + "Flags are owner-review items recorded in [`TODO.md`](../../../TODO.md).", "",
            "<!-- toc:start -->", "## Contents", "",
        };
        text.AddRange(layers.Select((l, i) => $"{i + 1}. [{l} Layer](./{names[i]})"));
        text.AddRange(["", "### List of Tables", ""]);
        text.AddRange(layers.Select((l, i) => $"{i + 1}. [Table {i + 1} — {l} projects](./{names[i]})"));
        text.AddRange(["<!-- toc:end -->", ""]);
        return string.Join('\n', text);
    }

    private static List<(string Directory, string Name)> Projects(string layerFolder)
    {
        var found = new List<(string, string)>();
        Walk(layerFolder);
        return [.. found.OrderBy(p => p.Item2.ToLowerInvariant(), StringComparer.Ordinal)];

        void Walk(string directory)
        {
            foreach (var file in Directory.EnumerateFiles(directory, "*.csproj"))
            {
                found.Add((directory, Path.GetFileNameWithoutExtension(file)));
            }

            foreach (var child in Directory.EnumerateDirectories(directory).Where(d => !_skip.Contains(Path.GetFileName(d))).Order(StringComparer.Ordinal))
            {
                Walk(child);
            }
        }
    }

    private static bool IsTest(string name) =>
        name.EndsWith(".Tests", StringComparison.Ordinal) || name.Contains(".Tests.", StringComparison.Ordinal) || name.EndsWith(".Test", StringComparison.Ordinal);

    private static (string Purpose, bool HasReadme) Purpose(string directory, string name)
    {
        var candidates = new List<string>();
        if (name.StartsWith("OoBDev.", StringComparison.Ordinal))
        {
            candidates.Add($"README.{name["OoBDev.".Length..]}.md");
        }

        candidates.AddRange([$"README.{name}.md", "README.md", "readme.md"]);
        foreach (var candidate in candidates)
        {
            foreach (var folder in new[] { directory, Path.GetDirectoryName(directory) })
            {
                if (folder is null)
                {
                    continue;
                }

                var path = Path.Combine(folder, candidate);
                if (File.Exists(path) && (folder == directory || candidate.StartsWith("README." + name, StringComparison.Ordinal)))
                {
                    return (Summary(path), true);
                }
            }
        }

        return (string.Empty, false);
    }

    private static string Summary(string path)
    {
        var text = File.ReadAllText(path).Replace("\r", string.Empty, StringComparison.Ordinal);
        text = _fences.Replace(_comments.Replace(text, string.Empty), string.Empty);
        foreach (var paragraph in _paragraphs.Split(text))
        {
            var lines = paragraph.Split('\n').Select(l => l.Trim()).Where(l => l.Length > 0).ToList();
            if (lines.Count == 0 || new[] { "#", "|", "-", "*", ">", "!", "[!", "<" }.Any(p => lines[0].StartsWith(p, StringComparison.Ordinal)))
            {
                continue;
            }

            var sentence = _links.Replace(string.Join(' ', lines), "$1").Replace('|', '/').Replace("`", string.Empty, StringComparison.Ordinal);
            var match = _sentence.Match(sentence);
            return (match.Success ? match.Groups[1].Value : sentence[..Math.Min(200, sentence.Length)]).Trim();
        }

        return string.Empty;
    }
}
